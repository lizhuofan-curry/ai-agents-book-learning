"""3-8第一步：官方七题、刑法单文档，单次与预标注分解查询的离线对照。"""
import argparse
from collections import Counter
from datetime import datetime, timedelta, timezone
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import time

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT/'官方资料/upstream'
OFFICIAL = UPSTREAM/'chapter3/agentic-rag'
MANIFEST = ROOT/'官方资料/manifest.json'
DATASET = OFFICIAL/'evaluation/offline_qa.json'
CHINA = timezone(timedelta(hours=8))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def dump(path, obj):
    temp = path.with_suffix('.json.tmp')
    temp.write_text(json.dumps(obj, ensure_ascii=False, indent=2, allow_nan=False)+'\n', encoding='utf-8')
    temp.replace(path)


def tokenize(text):
    """固定官方标准库fallback，不随jieba是否安装而改变。"""
    tokens = []
    for part in re.findall(r'[a-zA-Z0-9]+|[一-鿿]+', text):
        if part[0].isascii():
            tokens.append(part.lower())
        else:
            tokens.extend(part)
            tokens.extend(part[i:i+2] for i in range(len(part)-1))
    return tokens


def leading(text):
    match = re.match(r'^第[一二三四五六七八九十百千零两0-9]+条(?:之[一二三四五六七八九十0-9]+)?', text.strip())
    return match.group() if match else ''


def load_sources():
    manifest = json.loads(MANIFEST.read_text(encoding='utf-8'))
    if manifest['commit'] != 'dbc046eb896ac4e39aa19c7774c8bf49583b89a6':
        raise ValueError('官方版本发生变化')
    for entry in manifest['files']:
        path = (UPSTREAM/entry['path']).resolve()
        if not path.is_relative_to(UPSTREAM.resolve()) or sha(path) != entry['sha256']:
            raise ValueError('官方资料哈希失败：'+entry['path'])
    spec = importlib.util.spec_from_file_location('rag_offline_frozen', OFFICIAL/'offline_retriever.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    # 官方文件不改，仅在本次加载实例中明确选择其标准库分词路线。
    module._tokenize = tokenize
    retriever = module.OfflineRetriever(str(OFFICIAL/'laws'))
    if len(retriever.documents) != 1 or not retriever.chunks:
        raise ValueError('本步只接受固定刑法单文档')
    dataset = json.loads(DATASET.read_text(encoding='utf-8'))
    ids = [case['id'] for case in dataset['cases']]
    if len(ids) != 7 or len(set(ids)) != 7:
        raise ValueError('官方七题配置变化')
    articles = {leading(c['text']) for c in retriever.chunks}
    for case in dataset['cases']:
        gold = case['gold_articles']
        if not gold or len(gold) != len(set(gold)) or not set(gold) <= articles:
            raise ValueError('金标准为空、重复或不在语料中')
    return retriever, dataset, manifest


def evidence(hits, gold):
    found = {leading(hit['text']) for hit in hits}
    covered = [g for g in gold if g in found]
    return {'covered': covered, 'missing': [g for g in gold if g not in found],
            'recall': len(covered)/len(gold)}


def search_trace(retriever, query, top_k):
    started = time.perf_counter()
    hits = retriever.search(query, top_k)
    return {'query': query, 'top_k': top_k, 'tokens': tokenize(query),
            'elapsed_seconds': time.perf_counter()-started, 'hits': hits}


def run_case(retriever, case, top_k):
    gold = case['gold_articles']
    naive = search_trace(retriever, case['naive_query'], top_k)
    steps, union, seen = [], [], set()
    for query in case['subqueries']:
        step = search_trace(retriever, query, top_k)
        for hit in step['hits']:
            if hit['chunk_id'] not in seen:
                union.append(hit)
                seen.add(hit['chunk_id'])
        step['cumulative_evidence'] = evidence(union, gold)
        steps.append(step)
    # 辅助控制：单次查询扩大到相同最大返回位置预算。
    # 这不是等计算量控制，也不消除预标注改写带来的信息优势。
    budget = top_k * len(steps)
    wider = search_trace(retriever, case['naive_query'], budget)
    return {'id': case['id'], 'question': case['question'], 'difficulty': case['difficulty'],
            'gold_articles': gold,
            'naive': {'steps': [naive], 'evidence': evidence(naive['hits'], gold)},
            'decomposed': {'query_origin': 'official pre-labeled subqueries; not generated by a model',
                           'steps': steps, 'union_hits': union, 'evidence': evidence(union, gold)},
            'wider_single': {'steps': [wider], 'candidate_position_budget': budget,
                             'evidence': evidence(wider['hits'], gold)}}


def summarize(results):
    summary = {}
    for name, rows in [('overall', results), ('easy', [r for r in results if r['difficulty']=='easy']),
                       ('hard', [r for r in results if r['difficulty']=='hard'])]:
        if not rows:
            continue
        summary[name] = {'count': len(rows)}
        for mode in ('naive', 'decomposed', 'wider_single'):
            summary[name][mode+'_macro_recall'] = sum(r[mode]['evidence']['recall'] for r in rows)/len(rows)
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--preview', action='store_true')
    parser.add_argument('--top-k', type=int, default=5)
    args = parser.parse_args()
    if not 1 <= args.top_k <= 20:
        parser.error('--top-k必须为1到20')
    retriever, dataset, manifest = load_sources()
    print('3-8第一步：单次查询 vs 官方预标注分解查询；仅检索，不生成回答。')
    print('固定刑法文档：', len(retriever.documents), '；分块：', len(retriever.chunks), '；题数：', len(dataset['cases']))
    print('固定标准库中文单字/双字分词；每次Top-K：', args.top_k)
    print('模型/嵌入/网络请求均0；无需启动Ollama。')
    print('本步不是模型自主规划，也不是288文档全库或真实法律问答验收。')
    if args.preview:
        print('RAG_RETRIEVAL_PREVIEW_ONLY：哈希、索引和全部目标条文存在性核验通过；未执行正式查询。')
        return 0
    directory = ROOT/'运行结果'/('retrieval_compare_'+datetime.now(CHINA).strftime('%Y%m%d_%H%M%S_%f'))
    directory.mkdir(parents=True, exist_ok=False)
    record = {'status': 'running', 'created_at': datetime.now(CHINA).isoformat(),
        'script_sha256': sha(Path(__file__)), 'manifest_sha256': sha(MANIFEST), 'manifest': manifest,
        'dataset_sha256': sha(DATASET), 'top_k': args.top_k,
        'document_count': len(retriever.documents), 'chunk_count': len(retriever.chunks),
        'tokenizer': 'official standard-library fallback pinned: Chinese unigrams+bigrams and ASCII words',
        'model_requests': 0, 'embedding_requests': 0, 'network_requests': 0,
        'metric': 'macro mean of per-case exact leading-article evidence recall; not answer accuracy',
        'scope': 'one complete official criminal-law document; seven official cases; pre-labeled decomposition',
        'results': []}
    path = directory/'record.json'
    dump(path, record)
    try:
        for case in dataset['cases']:
            row = run_case(retriever, case, args.top_k)
            record['results'].append(row)
            dump(path, record)
            print('\n', row['id'], row['question'])
            print('目标条文：', ' / '.join(row['gold_articles']))
            for mode, label in [('naive', '单次'), ('decomposed', '预标注分解'), ('wider_single', '单次扩大候选')]:
                result = row[mode]
                print(label, '召回：', f"{result['evidence']['recall']:.1%}", '缺失：', result['evidence']['missing'])
                for step in result['steps']:
                    print('  查询：', step['query'])
                    for hit in step['hits']:
                        print('   ', hit['chunk_id'], leading(hit['text']), 'BM25=', round(hit['score'], 4))
                    if 'cumulative_evidence' in step:
                        print('  累计命中：', step['cumulative_evidence']['covered'])
        record['summary'] = summarize(record['results'])
        print('\n汇总（按题平均证据召回）：')
        print(json.dumps(record['summary'], ensure_ascii=False, indent=2))
        if sha(MANIFEST) != record['manifest_sha256']:
            raise ValueError('运行期间资料清单发生变化')
        load_sources()
        record['status'] = 'retrieval_comparison_saved_review_pending'
        dump(path, record)
        print('RAG_RETRIEVAL_COMPARISON_SAVED：查询、完整片段及指标已保存，待核对。')
        print('记录路径：', path)
        return 0
    except (Exception, KeyboardInterrupt) as error:
        record.update(status='incomplete', error={'type': type(error).__name__, 'message': str(error)})
        dump(path, record)
        print('本步未完成：', record['error'])
        print('记录路径：', path)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
